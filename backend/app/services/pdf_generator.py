"""Professional PDF report generation using ReportLab."""

import os
from typing import Any, Dict, List
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import HRFlowable, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from app.core.config import settings
from app.monitoring.logger import logger


class PDFReportGenerator:
    """Generates publication-quality PDF reports for research outputs."""

    @classmethod
    def generate_pdf(
        cls,
        report_id: str,
        title: str,
        executive_summary: str,
        sections: List[Dict[str, Any]],
        sources: List[Dict[str, Any]],
        verification_passed: bool = True,
    ) -> str:
        """Create a styled PDF document and return the absolute output file path."""
        os.makedirs(settings.REPORT_OUTPUT_DIR, exist_ok=True)
        output_filename = f"nexus_report_{report_id}.pdf"
        output_path = os.path.join(settings.REPORT_OUTPUT_DIR, output_filename)

        doc = SimpleDocTemplate(
            output_path,
            pagesize=letter,
            rightMargin=54,
            leftMargin=54,
            topMargin=54,
            bottomMargin=54,
        )

        styles = getSampleStyleSheet()

        # Custom styles
        header_color = colors.HexColor("#0f172a")
        accent_color = colors.HexColor("#3b82f6")
        text_dark = colors.HexColor("#1e293b")
        text_muted = colors.HexColor("#64748b")

        title_style = ParagraphStyle(
            "ReportTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=22,
            leading=26,
            textColor=header_color,
            spaceAfter=8,
        )

        subtitle_style = ParagraphStyle(
            "ReportSubtitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=11,
            leading=14,
            textColor=text_muted,
            spaceAfter=15,
        )

        h1_style = ParagraphStyle(
            "ReportH1",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=15,
            leading=19,
            textColor=accent_color,
            spaceBefore=14,
            spaceAfter=6,
            keepWithNext=True,
        )

        body_style = ParagraphStyle(
            "ReportBody",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=10,
            leading=14,
            textColor=text_dark,
            spaceAfter=6,
        )

        callout_style = ParagraphStyle(
            "ReportCallout",
            parent=styles["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#334155"),
        )

        story = []

        # Document Header
        story.append(Paragraph("NEXUS AI | Autonomous Intelligence Platform", subtitle_style))
        story.append(Paragraph(title, title_style))
        verification_badge = "VERIFIED (Claims Grounded)" if verification_passed else "FLAGGED FOR REVIEW"
        story.append(
            Paragraph(
                f"Generated by Multi-Agent Workflow • Quality Status: <b>{verification_badge}</b>",
                subtitle_style,
            )
        )
        story.append(HRFlowable(width="100%", thickness=1.5, color=accent_color, spaceBefore=4, spaceAfter=14))

        # Executive Summary Box
        story.append(Paragraph("1. Executive Summary", h1_style))
        summary_paragraphs = [
            Paragraph(f"<b>Key Synthesis:</b> {executive_summary}", callout_style)
        ]
        summary_table = Table([[summary_paragraphs]], colWidths=[500])
        summary_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f1f5f9")),
                ("LEFTPADDING", (0, 0), (-1, -1), 12),
                ("RIGHTPADDING", (0, 0), (-1, -1), 12),
                ("TOPPADDING", (0, 0), (-1, -1), 10),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ])
        )
        story.append(summary_table)
        story.append(Spacer(1, 10))

        # Core Report Sections
        for section in sections:
            sec_title = section.get("title", "")
            sec_content = section.get("content", "")
            if not sec_content or "Executive Summary" in sec_title:
                continue

            story.append(Paragraph(sec_title, h1_style))
            # Split lines / paragraphs
            for line in sec_content.split("\n\n"):
                line_clean = line.strip().replace("<", "&lt;").replace(">", "&gt;")
                if line_clean:
                    story.append(Paragraph(line_clean, body_style))
            story.append(Spacer(1, 6))

        # References Section
        if sources:
            story.append(Paragraph("References & Verified Citations", h1_style))
            for src in sources:
                idx = src.get("source_index", 1)
                stitle = src.get("title", "Untitled Source").replace("<", "&lt;").replace(">", "&gt;")
                surl = src.get("url") or "Uploaded Research Document"
                stype = src.get("source_type", "web").upper()
                story.append(
                    Paragraph(
                        f"<b>[{idx}] {stitle}</b> ({stype})<br/>"
                        f"<font color='#3b82f6'><u>{surl}</u></font>",
                        body_style,
                    )
                )
                story.append(Spacer(1, 3))

        try:
            doc.build(story)
            logger.info(f"Report PDF generated at {output_path}")
            return output_path
        except Exception as e:
            logger.error(f"Error building PDF with ReportLab: {e}")
            return ""

