"""Research models covering projects, plans, agents, sources, findings, and verification."""

from typing import List, Optional, TYPE_CHECKING
from sqlalchemy import Boolean, Float, ForeignKey, Integer, String, Text, JSON
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.database.base import Base, TimestampMixin, UUIDMixin

if TYPE_CHECKING:
    from app.models.user import User
    from app.models.report import Report, UsageRecord


class ResearchProject(Base, UUIDMixin, TimestampMixin):
    """Core research project entity."""
    __tablename__ = "research_projects"

    user_id: Mapped[str] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False)
    title: Mapped[str] = mapped_column(String(500), nullable=False)
    research_question: Mapped[str] = mapped_column(Text, nullable=False)
    mode: Mapped[str] = mapped_column(String(50), default="deep", nullable=False)  # quick, deep, academic
    depth: Mapped[str] = mapped_column(String(50), default="standard", nullable=False)  # standard, exhaustive
    max_sources: Mapped[int] = mapped_column(Integer, default=10, nullable=False)
    include_academic: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    selected_document_ids: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    status: Mapped[str] = mapped_column(
        String(50), default="pending_plan", index=True, nullable=False
    )  # pending_plan, plan_ready, in_progress, completed, failed, cancelled
    error_message: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Relationships
    user: Mapped["User"] = relationship("User", back_populates="research_projects")
    plan: Mapped[Optional["ResearchPlan"]] = relationship(
        "ResearchPlan", back_populates="project", uselist=False, cascade="all, delete-orphan"
    )
    tasks: Mapped[List["ResearchTask"]] = relationship(
        "ResearchTask", back_populates="project", cascade="all, delete-orphan"
    )
    agent_executions: Mapped[List["AgentExecution"]] = relationship(
        "AgentExecution", back_populates="project", cascade="all, delete-orphan"
    )
    sources: Mapped[List["ResearchSource"]] = relationship(
        "ResearchSource", back_populates="project", cascade="all, delete-orphan"
    )
    findings: Mapped[List["ExtractedFinding"]] = relationship(
        "ExtractedFinding", back_populates="project", cascade="all, delete-orphan"
    )
    verification_results: Mapped[List["VerificationResult"]] = relationship(
        "VerificationResult", back_populates="project", cascade="all, delete-orphan"
    )
    report: Mapped[Optional["Report"]] = relationship(
        "Report", back_populates="project", uselist=False, cascade="all, delete-orphan"
    )
    usage_records: Mapped[List["UsageRecord"]] = relationship(
        "UsageRecord", back_populates="project", cascade="all, delete-orphan"
    )


class ResearchPlan(Base, UUIDMixin, TimestampMixin):
    """Structured research plan generated by the Planner Agent."""
    __tablename__ = "research_plans"

    project_id: Mapped[str] = mapped_column(
        ForeignKey("research_projects.id", ondelete="CASCADE"), unique=True, index=True, nullable=False
    )
    domain: Mapped[str] = mapped_column(String(255), default="General", nullable=False)
    complexity: Mapped[str] = mapped_column(String(50), default="Medium", nullable=False)
    objectives: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    subtasks: Mapped[List[dict]] = mapped_column(JSON, default=list, nullable=False)
    search_queries: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    expected_evidence: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    strategy: Mapped[str] = mapped_column(Text, nullable=False)
    is_approved: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    user_feedback: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    project: Mapped["ResearchProject"] = relationship("ResearchProject", back_populates="plan")


class ResearchTask(Base, UUIDMixin, TimestampMixin):
    """Subtask managed in the research pipeline."""
    __tablename__ = "research_tasks"

    project_id: Mapped[str] = mapped_column(
        ForeignKey("research_projects.id", ondelete="CASCADE"), index=True, nullable=False
    )
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    agent_name: Mapped[str] = mapped_column(String(100), nullable=False)
    priority: Mapped[int] = mapped_column(Integer, default=1, nullable=False)
    status: Mapped[str] = mapped_column(String(50), default="pending", nullable=False)  # pending, running, completed, failed
    result_data: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)

    project: Mapped["ResearchProject"] = relationship("ResearchProject", back_populates="tasks")


class AgentExecution(Base, UUIDMixin, TimestampMixin):
    """Execution trace of an autonomous agent in the LangGraph workflow."""
    __tablename__ = "agent_executions"

    project_id: Mapped[str] = mapped_column(
        ForeignKey("research_projects.id", ondelete="CASCADE"), index=True, nullable=False
    )
    agent_name: Mapped[str] = mapped_column(String(100), index=True, nullable=False)
    status: Mapped[str] = mapped_column(
        String(50), default="idle", index=True, nullable=False
    )  # idle, running, completed, failed, retry
    input_state: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    output_state: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    error_message: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    retry_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    execution_time_seconds: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)

    project: Mapped["ResearchProject"] = relationship("ResearchProject", back_populates="agent_executions")


class ResearchSource(Base, UUIDMixin, TimestampMixin):
    """Evidence source collected from web, arXiv, Semantic Scholar, Crossref, or PDFs."""
    __tablename__ = "research_sources"

    project_id: Mapped[str] = mapped_column(
        ForeignKey("research_projects.id", ondelete="CASCADE"), index=True, nullable=False
    )
    source_index: Mapped[int] = mapped_column(Integer, default=1, nullable=False)
    title: Mapped[str] = mapped_column(String(500), nullable=False)
    url: Mapped[Optional[str]] = mapped_column(String(1000), nullable=True)
    source_type: Mapped[str] = mapped_column(
        String(50), default="web", index=True, nullable=False
    )  # web, semantic_scholar, arxiv, crossref, pdf
    authors: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)
    publication_date: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    snippet: Mapped[str] = mapped_column(Text, nullable=False)
    full_text: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    reliability_score: Mapped[float] = mapped_column(Float, default=0.8, nullable=False)
    relevance_score: Mapped[float] = mapped_column(Float, default=0.8, nullable=False)

    project: Mapped["ResearchProject"] = relationship("ResearchProject", back_populates="sources")
    findings: Mapped[List["ExtractedFinding"]] = relationship(
        "ExtractedFinding", back_populates="source", cascade="all, delete-orphan"
    )


class ExtractedFinding(Base, UUIDMixin, TimestampMixin):
    """Atomic factual, statistical, methodological, or conceptual finding."""
    __tablename__ = "extracted_findings"

    project_id: Mapped[str] = mapped_column(
        ForeignKey("research_projects.id", ondelete="CASCADE"), index=True, nullable=False
    )
    source_id: Mapped[Optional[str]] = mapped_column(
        ForeignKey("research_sources.id", ondelete="SET NULL"), nullable=True
    )
    finding_type: Mapped[str] = mapped_column(
        String(50), default="fact", index=True, nullable=False
    )  # fact, statistic, methodology, concept
    statement: Mapped[str] = mapped_column(Text, nullable=False)
    evidence_quote: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    confidence: Mapped[float] = mapped_column(Float, default=0.9, nullable=False)
    tags: Mapped[List[str]] = mapped_column(JSON, default=list, nullable=False)

    project: Mapped["ResearchProject"] = relationship("ResearchProject", back_populates="findings")
    source: Mapped[Optional["ResearchSource"]] = relationship("ResearchSource", back_populates="findings")


class VerificationResult(Base, UUIDMixin, TimestampMixin):
    """Claim verification outcome produced by the Verification Agent."""
    __tablename__ = "verification_results"

    project_id: Mapped[str] = mapped_column(
        ForeignKey("research_projects.id", ondelete="CASCADE"), index=True, nullable=False
    )
    claim: Mapped[str] = mapped_column(Text, nullable=False)
    status: Mapped[str] = mapped_column(
        String(50), default="verified", index=True, nullable=False
    )  # verified, unsupported, contradicted
    confidence_score: Mapped[float] = mapped_column(Float, default=0.9, nullable=False)
    supporting_source_indices: Mapped[List[int]] = mapped_column(JSON, default=list, nullable=False)
    contradiction_details: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    required_additional_research: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    project: Mapped["ResearchProject"] = relationship("ResearchProject", back_populates="verification_results")

